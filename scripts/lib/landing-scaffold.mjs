// Landing isolation & portability.
//
// THE PROBLEM. `content/landing-base` carries no `.git` and no `.gitignore`,
// and `copyTemplate()` excludes `.git` anyway, so a generated landing had
// neither. Sitting under `outputs/<slug>/`, it therefore resolved the PARENT
// repository: `git rev-parse --show-toplevel` inside a landing returned the
// generator's own root. Consequences, all real:
//   - `git add .` inside a landing stages against the parent's index;
//   - the landing cannot be pushed to its own GitHub repo or imported by
//     Vercel without dragging the whole generator along;
//   - nothing inside the landing is ignored by rules meant for a landing.
//
// THE FIX is two files and one command, all local to the output: a `.gitignore`
// written for an Astro/Node project, and `git init -b main`. No commit, no
// remote, no push — the landing becomes its own repository and stops being a
// subdirectory of someone else's.
//
// NOT ADDRESSED HERE, on purpose: dependency installation. The template's
// `package.json` and `pnpm-lock.yaml` are already copied verbatim, so a clean
// `pnpm install && pnpm build` inside the output is self-sufficient. Copying
// `node_modules` would bloat every landing and reintroduce exactly the shared,
// symlinked store this phase exists to eliminate.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/**
 * The ignore rules a standalone Astro landing needs. `.env.example` is
 * deliberately re-admitted after `.env.*`: it documents which variables the
 * landing expects and must ship, while never carrying a real value.
 */
export const LANDING_GITIGNORE = [
  '# Generated by scripts/generate-landing.mjs — this landing is its own repo.',
  '',
  'node_modules/',
  'dist/',
  '.astro/',
  '.vercel/',
  '.output/',
  '',
  '# Secrets never belong in the repo. .env carries the landing\'s own',
  '# PUBLIC_SHOPIFY_* configuration and stays local.',
  '.env',
  '.env.*',
  '!.env.example',
  '',
  '.DS_Store',
  '*.log',
  '',
];

/**
 * Writes the landing's `.gitignore`.
 *
 * If the template ever grows one of its own, its rules are PRESERVED and the
 * missing ones appended — silently overwriting an existing ignore file could
 * drop a rule someone added deliberately, and this function has no way to
 * know which rules matter.
 */
export function writeLandingGitignore(outDir) {
  const target = path.join(outDir, '.gitignore');
  const required = LANDING_GITIGNORE.filter((l) => l && !l.startsWith('#'));

  if (!existsSync(target)) {
    writeFileSync(target, LANDING_GITIGNORE.join('\n'));
    return { created: true, appended: [] };
  }

  const existing = readFileSync(target, 'utf-8');
  const lines = existing.split('\n').map((l) => l.trim());
  const missing = required.filter((rule) => !lines.includes(rule));

  if (missing.length > 0) {
    writeFileSync(
      target,
      `${existing.replace(/\n*$/, '\n')}\n# Added by scripts/generate-landing.mjs\n${missing.join('\n')}\n`,
    );
  }
  return { created: false, appended: missing };
}

/**
 * Turns the output directory into its own git repository.
 *
 * `git init` is idempotent, but an existing `.git` is left completely alone:
 * re-running the generator with --force must never discard a history the
 * operator has already started in that landing.
 *
 * Deliberately does NOT commit, add a remote, or push — creating history is
 * the operator's decision, not a side effect of generation.
 */
export function initLandingRepo(outDir, { runGit = defaultRunGit } = {}) {
  if (existsSync(path.join(outDir, '.git'))) {
    return { initialized: false, reason: 'already-a-repo' };
  }

  try {
    // -b main avoids depending on the machine's init.defaultBranch.
    runGit(['init', '-b', 'main'], outDir);
  } catch (cause) {
    // A landing without its own repo is still a usable, buildable project, so
    // this is reported rather than fatal — but it IS reported, never swallowed.
    return { initialized: false, reason: `git-init-failed: ${cause?.message ?? cause}` };
  }

  return { initialized: true, reason: null };
}

function defaultRunGit(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'] });
}

/**
 * Resolves the git root a path belongs to. Used by the contract tests to prove
 * a landing is its OWN repository and not a subdirectory of the generator's.
 */
export function gitToplevelOf(dir, { runGit = defaultRunGit } = {}) {
  try {
    return runGit(['rev-parse', '--show-toplevel'], dir).trim();
  } catch {
    return null;
  }
}
